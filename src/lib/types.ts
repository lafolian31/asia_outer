export type Role = "admin" | "editor" | "viewer";
export type Kind = "log" | "plan" | "resource";
export type Entry = {
  id: string;
  work_groups?: string[] | null;
  work_items?: { group: string; task: string }[] | null;
  crop_names?: string[] | null;
  zone_names?: string[] | null;
  plan_ids?: string[] | null;
  record_type?: "farm" | "activity" | null;
  work_group?: string;
  work_task?: string;
  activity_category?: string;
  quantity?: number | null;
  quantity_unit?: string;
  participant_ids?: string[];
  kind: Kind;
  title: string;
  body: string;
  work_date: string | null;
  target_year: number | null;
  start_date: string | null;
  end_date: string | null;
  status: string;
  actual_date: string | null;
  result: string;
  zone: string;
  crop: string;
  assignee: string | null;
  plan_id: string | null;
  category: string;
  url: string;
  author_id: string;
  created_at: string;
  updated_at: string;
  updated_by: string;
  completed_at: string | null;
  completed_by: string | null;
  deleted_at: string | null;
  deleted_by: string | null;
  version: number;
};
export type Member = {
  user_id: string;
  display_name: string;
  role: Role;
  active: boolean;
};
export type Asset = {
  id: string;
  entry_id: string;
  path: string;
  name: string;
  mime: string;
  size: number;
  ready: boolean;
  author_id: string;
  deleted_at: string | null;
};
export type Settings = {
  name: string;
  zones: string[];
  crops: string[];
  resource_categories?: string[];
  multi_recording?: boolean;
  work_catalog?: Record<string, string[]>;
  version: number;
};
export type Snapshot = {
  entries: Entry[];
  members: Member[];
  assets: Asset[];
  settings: Settings;
};

export type Comment = {
  id: string;
  entry_id: string;
  author_id: string;
  body: string;
  created_at: string;
  updated_at: string;
  updated_by: string;
  deleted_at: string | null;
  version: number;
};
export type ReactionKind = "like" | "love" | "laugh" | "wow";
export type Reaction = {
  id: string;
  entry_id: string;
  user_id: string;
  kind: ReactionKind;
  updated_at: string;
};
